# IDENTIFY STUDENT RISK FACTORS
# ============================================================

def identify_risk_factors(profile):

    factors = []


    # Low GPA
    if profile.gpa < 2.0:
        factors.append("low_gpa")


    # Poor attendance
    if profile.attendance_pct < 75:
        factors.append("poor_attendance")


    # Missed assignments
    if profile.missed_assignments >= 3:
        factors.append("missed_assignments")


    # Low participation
    if profile.participation_score < 5:
        factors.append("low_participation")


    return factors

