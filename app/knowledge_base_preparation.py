def build_knowledge_context(profile):

    risk_guidance = get_risk_guidance(
        profile.risk_level
    )

    risk_factors = identify_risk_factors(
        profile
    )

    factor_guidance = get_factor_guidance(
        risk_factors
    )


    context = {

        "risk_level":
            profile.risk_level,

        "risk_priority":
            risk_guidance["priority"],

        "risk_description":
            risk_guidance["description"],

        "identified_risk_factors":
            risk_factors,

        "general_actions":
            risk_guidance["recommended_actions"],

        "factor_guidance":
            factor_guidance
    }


    return context

