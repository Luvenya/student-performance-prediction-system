# FORMAT KNOWLEDGE FOR GEMINI
# ============================================================

def format_knowledge_for_llm(profile):

    context = build_knowledge_context(
        profile
    )


    output = []


    output.append(
        f"Risk Level: {context['risk_level']}"
    )


    output.append(
        f"Priority: {context['risk_priority']}"
    )


    output.append(
        f"Risk Description: "
        f"{context['risk_description']}"
    )


    output.append(
        "\nRelevant Risk Factors:"
    )


    for factor in context[
        "identified_risk_factors"
    ]:

        output.append(
            f"- {factor.replace('_', ' ').title()}"
        )


    output.append(
        "\nRecommended Actions:"
    )


    for action in context[
        "general_actions"
    ]:

        output.append(
            f"- {action}"
        )


    output.append(
        "\nRisk-Factor Specific Guidance:"
    )


    for item in context[
        "factor_guidance"
    ]:

        output.append(
            f"\n{item['factor'].replace('_', ' ').title()}:"
        )


        for action in item[
            "recommended_actions"
        ]:

            output.append(
                f"- {action}"
            )


    return "\n".join(output)

