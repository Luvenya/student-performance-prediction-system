# RETRIEVE RISK-FACTOR GUIDANCE
# ============================================================

def get_factor_guidance(risk_factors):

    factor_database = loaded_knowledge_base[
        "risk_factors"
    ]

    guidance = []


    for factor in risk_factors:

        if factor in factor_database:

            guidance.append({

                "factor": factor,

                "description":
                    factor_database[factor]["description"],

                "recommended_actions":
                    factor_database[factor]["recommended_actions"]
            })


    return guidance

