def generate_intervention_recommendation(profile):

    """
    Sends the student's risk information to Gemini
    and returns an AI-generated intervention recommendation.
    """

    # --------------------------------------------------------
    # STEP 1: Build the engineered user prompt
    # --------------------------------------------------------

    user_prompt = build_prompt(profile)


    # --------------------------------------------------------
    # STEP 2: Combine system instructions + user prompt
    # --------------------------------------------------------

    full_prompt = f"""
{SYSTEM_PROMPT}

Student information and risk assessment:

{user_prompt}

Based on the information above, provide a clear and practical
intervention recommendation for this student.
"""


    # --------------------------------------------------------
    # STEP 3: Send prompt to Gemini API
    # --------------------------------------------------------

    interaction = client.interactions.create(

        # Gemini model
        model="gemini-3.6-flash",

        # Combined system instructions and student information
        input=full_prompt
    )


    # --------------------------------------------------------
    # STEP 4: Extract Gemini's response
    # --------------------------------------------------------

    recommendation = interaction.output_text


    return recommendation.strip()


