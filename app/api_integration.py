"""
Step 1: Prompt Engineering
Project 6 - Student Performance Prediction System

Goal:
Given a student's risk data (output of the ML model), build a
well-engineered prompt that an LLM (Claude) can use to generate
a clear, actionable intervention recommendation.

This file contains:
1. A fixed SYSTEM_PROMPT defining the LLM's role
2. Few-shot examples to guide output format/quality
3. A dynamic prompt builder function
4. A small test harness to compare prompt versions
"""

from dataclasses import dataclass


# ----------------------------------------------------------------------
# 1. Student data structure (this is what the ML model will output
#    later in Step 4 - Initial Prototype)
# ----------------------------------------------------------------------
@dataclass
class StudentRiskProfile:
    student_id: str
    risk_level: str        # "Low" | "Medium" | "High"
    gpa: float
    attendance_pct: float
    missed_assignments: int
    participation_score: float  # 0-10


# ----------------------------------------------------------------------
# 2. System Prompt (fixed role definition for the LLM)
# ----------------------------------------------------------------------
SYSTEM_PROMPT = """You are an academic advisor assistant embedded in a
university early-warning system. You receive a student's academic risk
data and must produce ONE short, actionable intervention recommendation
for the instructor or academic advisor.

Rules:
- Be specific and actionable (avoid vague advice like "help the student").
- Base your recommendation on the actual risk factors given.
- Keep the response to 2-3 sentences maximum.
- Do not repeat the raw numbers back verbatim; interpret them.
- Tone: professional, supportive, concise.
- Output plain text only (no markdown, no headers).
"""


# ----------------------------------------------------------------------
# 3. Few-shot examples (guides the model toward consistent style/format)
# ----------------------------------------------------------------------
FEW_SHOT_EXAMPLES = [
    {
        "input": "Risk: High | GPA: 1.8 | Attendance: 52% | Missed "
                 "Assignments: 5 | Participation: 2/10",
        "output": "This student shows critical risk indicators across "
                  "attendance, assignments, and GPA. Recommend an "
                  "immediate one-on-one meeting with the academic "
                  "advisor and referral to the tutoring center this week."
    },
    {
        "input": "Risk: Medium | GPA: 2.6 | Attendance: 78% | Missed "
                 "Assignments: 2 | Participation: 5/10",
        "output": "Moderate risk driven mainly by inconsistent "
                  "assignment submission. Recommend a check-in email "
                  "from the instructor and enabling assignment deadline "
                  "reminders for this student."
    },
    {
        "input": "Risk: Low | GPA: 3.4 | Attendance: 91% | Missed "
                  "Assignments: 0 | Participation: 8/10",
        "output": "No intervention needed at this time. Continue routine "
                  "monitoring; performance is stable and on track."
    },
]


# ----------------------------------------------------------------------
# 4. Dynamic prompt builder
# ----------------------------------------------------------------------
def format_student_data(profile: StudentRiskProfile) -> str:
    """Turns a StudentRiskProfile into the compact text format used
    in the few-shot examples, so the model sees a consistent pattern."""
    return (
        f"Risk: {profile.risk_level} | GPA: {profile.gpa} | "
        f"Attendance: {profile.attendance_pct}% | "
        f"Missed Assignments: {profile.missed_assignments} | "
        f"Participation: {profile.participation_score}/10"
    )


def build_prompt(profile: StudentRiskProfile) -> str:
    """
    Builds the final user-turn prompt (few-shot + real student data)
    that will be sent to the LLM API in Step 2.
    """
    examples_block = "\n\n".join(
        f"Student data: {ex['input']}\nRecommendation: {ex['output']}"
        for ex in FEW_SHOT_EXAMPLES
    )

    student_block = format_student_data(profile)

    prompt = f"""Here are examples of the expected output format:

{examples_block}

Now generate a recommendation for this student:

Student data: {student_block}
Recommendation:"""

    return prompt


